"""### Understanding Quiver Plots in Analytics

A **Quiver Plot** is used to display vector fields—where each point has both a direction and a magnitude. In business analytics, we can use them to compare state changes (e.g., *Before vs After* or *Clear Weather vs Rain*):
- **Base Point (`x, y`)**: The starting condition (Average delivery time and rating under **Clear** weather).
- **Arrows (`dx, dy`)**: The shift in performance when conditions change to **Rain** (the direction shows if delivery times got longer and ratings got worse, while arrow length shows the severity of the impact).
"""

plt.figure(figsize=(8, 5))
plt.quiver(x, y, dx, dy, angles="xy", scale_units="xy", scale=1, color="#6A1B9A")
plt.scatter(x, y, color="grey")

for name in clear.index:
    plt.text(x[name] + dx[name], y[name] + dy[name] - 0.03, name, fontsize=7)   # label at the arrow tip

plt.xlim(x.min() - 1, (x + dx).max() + 2)
plt.ylim((y + dy).min() - 0.15, y.max() + 0.1)
plt.title("What rain does to each state (arrow: clear weather to rain)")
plt.xlabel("Average delivery time (minutes)")
plt.ylabel("Average rating")
